# tests/insn/insn.py
# ==================
#
# The generators of the instruction-model test (tests/insn/README.md).
#
#     insn.py jazz     TABLE            the Jasmin test program
#     insn.py header   TABLE            the C table of its exports
#     insn.py operands TABLE NAME       the operands of one entry
#     insn.py asm      TABLE ASM        check each export's instruction
#     insn.py wordeval TEMPLATE         WordEval.ec from WordEval.ec.in
#     insn.py lemmas   TABLE MODEL VECTORS NAME [control]
#                                       the EasyCrypt cases of one entry
#     insn.py mutants  MUTANTS TABLE    list the wrong models
#     insn.py mutate   MUTANTS ECLIB OUT NAME
#                                       a copy of ECLIB with one of them
#                                       (NAME -: an unchanged copy)
#
# A table has one entry per line: a name, one Jasmin statement and the
# mnemonic the statement must compile to.
#
#     sha256msg1  r = #SHA256MSG1(a, b);  sha256msg1
#
# In the statement, a to h are the operands: 128-bit words that the test
# program loads from the input buffer, a at byte 0, b at byte 16 and so
# on. r, s, t and u are the results, 128-bit words that it stores to the
# output buffer, r at byte 0, s at byte 16 and so on. The statement may
# also read the input buffer itself, through `src` (a load instruction
# under test reads [:u32 src + 4], say), and may be several statements
# separated by `;`. Each entry becomes one export,
#
#     export fn insn_<name>(reg u64 out src)
#
# that loads its operands, runs the statement and stores its results.
#
# lemmas reads that export's EasyCrypt model, as jasmin2ec extracted it,
# and writes one lemma per test vector: the procedure body as a chain of
# let bindings, every load from the input buffer replaced by the literal
# the vector holds at that address, the stores replaced by equations
# between the stored value and the bytes the processor wrote there. So
# each lemma evaluates exactly the operators, in exactly the argument
# order, that the extraction of the compiled statement uses. A control
# argument turns the cases into one that must fail to check:
#
#     --flip           one case, bit 0 of its first result flipped
#     --swap=X,Y       one case, operands X and Y exchanged
#
# The one case of a control is the first whose operands all differ.
#     --all            all cases, unchanged (used against a mutated model)

import os
import re
import sys

OPERANDS = "abcdefgh"
RESULTS = "rstu"
SLOT = 16


def die(msg):
    sys.stderr.write("insn.py: %s\n" % msg)
    sys.exit(2)


def read_table(path):
    entries = []
    with open(path) as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0] if line.lstrip().startswith("#") else line
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 3:
                die("%s:%d: expected NAME STATEMENT MNEMONIC" % (path, n))
            name, mnemonic = parts[0], parts[-1]
            stmt = line[len(name):].strip()
            stmt = stmt[: len(stmt) - len(mnemonic)].strip()
            if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
                die("%s:%d: bad name %r" % (path, n, name))
            if not stmt.endswith(";"):
                die("%s:%d: the statement must end with ';'" % (path, n))
            # Single lower-case letters are the operands and results.
            # Intrinsic names are upper case, so they cannot clash.
            letters = set(re.findall(r"(?<![\w#])([a-z])(?!\w)", stmt))
            ops = [c for c in OPERANDS if c in letters]
            res = [c for c in RESULTS if c in letters]
            other = letters - set(OPERANDS) - set(RESULTS)
            if other:
                die("%s:%d: unknown variables %s" % (path, n, " ".join(sorted(other))))
            if not res:
                die("%s:%d: the statement writes no result" % (path, n))
            if any(e["name"] == name for e in entries):
                die("%s:%d: duplicate name %s" % (path, n, name))
            entries.append(dict(name=name, stmt=stmt, mnemonic=mnemonic,
                                ops=ops, res=res, line=n))
    if not entries:
        die("%s: no entries" % path)
    return entries


def entry(entries, name):
    for e in entries:
        if e["name"] == name:
            return e
    die("no entry %s" % name)


# --------------------------------------------------------------------
# The Jasmin test program and its C table
# --------------------------------------------------------------------

def cmd_jazz(table):
    entries = read_table(table)
    out = ["/* Generated by tests/insn/insn.py jazz %s; do not edit. */"
           % os.path.basename(table)]
    for e in entries:
        regs = e["ops"] + [r for r in e["res"] if r not in e["ops"]]
        out.append("")
        out.append("export fn insn_%s(reg u64 out src)" % e["name"])
        out.append("{")
        out.append("  reg u128 %s;" % " ".join(regs))
        for c in e["ops"]:
            out.append("  %s = [:u128 src + %d];" % (c, SLOT * OPERANDS.index(c)))
        for s in re.findall(r"[^;]+;", e["stmt"]):
            out.append("  %s" % s.strip())
        for c in e["res"]:
            out.append("  [:u128 out + %d] = %s;" % (SLOT * RESULTS.index(c), c))
        out.append("}")
    print("\n".join(out))


def cmd_header(table):
    entries = read_table(table)
    out = ["/* Generated by tests/insn/insn.py header %s; do not edit. */"
           % os.path.basename(table), ""]
    for e in entries:
        out.append("void insn_%s(uint8_t *out, const uint8_t *src);" % e["name"])
    out.append("")
    out.append("static const struct insn insns[] = {")
    for e in entries:
        mask = sum(1 << OPERANDS.index(c) for c in e["ops"])
        out.append('  { "%s", insn_%s, 0x%02x, %d },'
                   % (e["name"], e["name"], mask, len(e["res"])))
    out.append("};")
    print("\n".join(out))


def cmd_operands(table, name):
    print(" ".join(entry(read_table(table), name)["ops"]))


def cmd_asm(table, asm):
    """Every export must contain its mnemonic: the test exercises the
    instruction only if the compiler emitted it."""
    entries = read_table(table)
    text = open(asm).read()
    bad = 0
    for e in entries:
        sym = "insn_" + e["name"]
        m = re.search(r"^_?%s:\n(.*?)(?=^\S|\Z)" % re.escape(sym), text, re.M | re.S)
        if not m:
            print("asm: %s: no code for %s" % (asm, sym))
            bad += 1
            continue
        ops = [l.split()[0].lower() for l in m.group(1).splitlines()
               if l.strip() and not l.strip().startswith(".")]
        n = ops.count(e["mnemonic"].lower())
        if n == 0:
            print("asm: %s does not contain %s" % (sym, e["mnemonic"]))
            bad += 1
        else:
            print("asm: %s: %s x%d" % (sym, e["mnemonic"], n))
    sys.exit(1 if bad else 0)


# --------------------------------------------------------------------
# WordEval.ec
# --------------------------------------------------------------------

SIZES = [8, 16, 32, 64, 128]
PACKS = [  # theory, lane bits, word bits, lanes
    ("W4u8", 8, 32, 4), ("W2u16", 16, 32, 2),
    ("W8u8", 8, 64, 8), ("W4u16", 16, 64, 4), ("W2u32", 32, 64, 2),
    ("W16u8", 8, 128, 16), ("W8u16", 16, 128, 8), ("W4u32", 32, 128, 4),
    ("W2u64", 64, 128, 2),
]


def cmd_wordeval(template):
    text = open(template).read()
    blocks = re.split(r"^\(\* @(size|pack)\b[^\n]*\n(.*?)^\(\* @end \*\)\n",
                      text, flags=re.M | re.S)
    out = [blocks[0]]
    for i in range(1, len(blocks), 3):
        kind, body, after = blocks[i], blocks[i + 1], blocks[i + 2]
        if kind == "size":
            for n in SIZES:
                out.append(body.replace("@N@", str(n)))
        else:
            for t, s, b, r in PACKS:
                out.append(body.replace("@T@", t).replace("@S@", str(s))
                           .replace("@B@", str(b)).replace("@R@", str(r)))
        out.append(after)
    sys.stdout.write("(* Generated by tests/insn/insn.py wordeval; do not edit. *)\n")
    sys.stdout.write("".join(out))


