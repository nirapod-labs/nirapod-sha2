def read_vectors(path, name):
    """Lines `NAME INDEX IN OUT`, IN and OUT in hexadecimal, byte 0 first."""
    vs = []
    with open(path) as f:
        for line in f:
            p = line.split()
            if len(p) == 4 and p[0] == name:
                vs.append((int(p[1]), bytes.fromhex(p[2]), bytes.fromhex(p[3])))
    if not vs:
        die("%s: no vectors for %s" % (path, name))
    return vs


def le(buf, off, bits):
    n = bits // 8
    if off < 0 or off + n > len(buf):
        die("access of %d bits at %d is outside the buffer" % (bits, off))
    return int.from_bytes(buf[off:off + n], "little")


def proc_body(model, name):
    text = open(model).read()
    m = re.search(r"proc insn_%s \(out:W64\.t, src:W64\.t\) : unit = \{\n(.*?)\n\s*return \(\);\n\s*\}"
                  % re.escape(name), text, re.S)
    if not m:
        die("%s: no procedure insn_%s" % (model, name))
    stmts = []
    for s in re.findall(r"[^;]*;", m.group(1), re.S):
        s = " ".join(s.split())
        if s.startswith("var "):
            continue
        stmts.append(s[:-1])
    return text, stmts


ADDR = r"\(W64\.to_uint \((src|out) \+ \(W64\.of_int (\d+)\)\)\)"
LOAD = re.compile(r"\(loadW(\d+) Glob\.mem " + ADDR + r"\)")
STORE = re.compile(r"Glob\.mem <- \(storeW(\d+) Glob\.mem " + ADDR + r" (.*)\)$")


def lemma_body(stmts, inp, outp, flip):
    lets, eqs = [], []
    for s in stmts:
        st = STORE.fullmatch(s)
        if st:
            bits, base, off, e = int(st.group(1)), st.group(2), int(st.group(3)), st.group(4)
            if base != "out":
                die("store to %s, not to the output buffer" % base)
            v = le(outp, int(off), bits)
            if flip and not eqs:
                v ^= 1
            eqs.append("%s = W%d.of_int %d" % (subst(e, inp), bits, v))
            continue
        a = re.fullmatch(r"(\(?[\w, ]+\)?) <- (.*)", s)
        if not a:
            die("statement not understood: %s" % s)
        lets.append("let %s = %s in" % (a.group(1), subst(a.group(2), inp)))
    if not eqs:
        die("the procedure stores nothing")
    return "\n  ".join(lets + ["(" + " /\\\n   ".join(eqs) + ")"])


def subst(e, inp):
    def load(m):
        bits, base, off = int(m.group(1)), m.group(2), int(m.group(3))
        if base != "src":
            die("load from %s, not from the input buffer" % base)
        return "(W%d.of_int %d)" % (bits, le(inp, off, bits))
    e = LOAD.sub(load, e)
    if "Glob.mem" in e:
        die("memory access not understood: %s" % e)
    return e


def cmd_lemmas(table, model, vectors, name, control=None):
    e = entry(read_table(table), name)
    header, stmts = proc_body(model, name)
    imp = re.search(r"^from Jasmin require import (\S+)\.$", header, re.M)
    if not imp:
        die("%s: no JModel import" % model)
    vs = read_vectors(vectors, name)
    if control not in (None, "--flip", "--all") and not control.startswith("--swap="):
        die("unknown control %s" % control)
    flip = control == "--flip"
    swap = None
    if control and control.startswith("--swap="):
        x, y = control[len("--swap="):].split(",")
        if x not in e["ops"] or y not in e["ops"]:
            die("%s has no operands %s and %s" % (name, x, y))
        swap = (SLOT * OPERANDS.index(x), SLOT * OPERANDS.index(y))
    if flip or swap:
        # The controls use one case, the first in which the operand slots
        # all differ from each other, so that exchanging two operands
        # changes the input.
        def distinct(inp):
            slots = [inp[SLOT * OPERANDS.index(c):][:SLOT] for c in e["ops"]]
            return len(set(slots)) == len(slots)
        vs = [v for v in vs if distinct(v[1])][:1]
        if not vs:
            die("%s: no vector with distinct operands for the controls" % name)
    print("(* Generated by tests/insn/insn.py lemmas %s; do not edit. *)" % name)
    print("require import AllCore IntDiv List.")
    print("from Jasmin require import %s." % imp.group(1))
    print("require import WordEval.")
    print()
    for k, inp, outp in vs:
        if swap:
            b = bytearray(inp)
            i, j = swap
            b[i:i + SLOT], b[j:j + SLOT] = inp[j:j + SLOT], inp[i:i + SLOT]
            inp = bytes(b)
        print("lemma %s_%d :\n  %s.\nproof. by cbv delta. qed.\n"
              % (name, k, lemma_body(stmts, inp, outp, flip)))


def read_mutants(path):
    muts, cur = [], None
    with open(path) as f:
        for n, line in enumerate(f, 1):
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            m = re.fullmatch(r"mutant\s+(\S+)\s*", line)
            if m:
                cur = dict(name=m.group(1), line=n)
                muts.append(cur)
                continue
            m = re.fullmatch(r"\s+(entries|file|from|to)\s+(.*?)\s*", line)
            if not m or cur is None or m.group(1) in cur:
                die("%s:%d: not understood" % (path, n))
            cur[m.group(1)] = m.group(2)
    for m in muts:
        for k in ("entries", "file", "from", "to"):
            if k not in m:
                die("%s:%d: mutant %s has no %s" % (path, m["line"], m["name"], k))
        m["entries"] = m["entries"].split()
        # \n in from and to stands for a newline, so that a change can be
        # anchored on text that is unique only across two lines.
        for k in ("from", "to"):
            m[k] = m[k].replace("\\n", "\n")
    if len(set(m["name"] for m in muts)) != len(muts):
        die("%s: duplicate mutant names" % path)
    return muts


def cmd_mutants(path, table):
    names = [e["name"] for e in read_table(table)]
    for m in read_mutants(path):
        for e in m["entries"]:
            if e not in names:
                die("mutant %s: no entry %s in %s" % (m["name"], e, table))
        print(m["name"], " ".join(m["entries"]))


def cmd_mutate(path, eclib, out, name):
    """Copy the .ec files of the EasyCrypt library ECLIB to OUT with the
    mutant NAME applied. Its text must occur exactly once. NAME `-` makes
    an unchanged copy, against which every case must still check."""
    muts = [m for m in read_mutants(path) if m["name"] == name]
    if name == "-":
        muts = [dict(name="-", file=None, **{"from": None, "to": None})]
    if not muts:
        die("%s: no mutant %s" % (path, name))
    m = muts[0]
    if m["file"] and not os.path.isfile(os.path.join(eclib, m["file"])):
        die("%s: no file %s" % (eclib, m["file"]))
    os.makedirs(out, exist_ok=True)
    for f in sorted(os.listdir(eclib)):
        if not f.endswith(".ec"):
            continue
        with open(os.path.join(eclib, f)) as src:
            text = src.read()
        if f == m["file"]:
            k = text.count(m["from"])
            if k != 1:
                die("mutant %s: %r occurs %d times in %s, not once" % (name, m["from"], k, f))
            text = text.replace(m["from"], m["to"])
        with open(os.path.join(out, f), "w") as dst:
            dst.write(text)


def main(argv):
    if len(argv) < 2:
        die("usage: see the head of this file")
    cmd, args = argv[1], argv[2:]
    if cmd == "jazz" and len(args) == 1:
        cmd_jazz(*args)
    elif cmd == "header" and len(args) == 1:
        cmd_header(*args)
    elif cmd == "operands" and len(args) == 2:
        cmd_operands(*args)
    elif cmd == "asm" and len(args) == 2:
        cmd_asm(*args)
    elif cmd == "wordeval" and len(args) == 1:
        cmd_wordeval(*args)
    elif cmd == "lemmas" and len(args) in (4, 5):
        cmd_lemmas(*args)
    elif cmd == "mutants" and len(args) == 2:
        cmd_mutants(*args)
    elif cmd == "mutate" and len(args) == 4:
        cmd_mutate(*args)
    else:
        die("usage: see the head of this file")


if __name__ == "__main__":
    main(sys.argv)
